import math

# Compute atan(22.855)
atan_val = math.atan(22.855)

# Compute cos(0.84886) in radians
cos_val = math.cos(0.84886)

# Sum them
sum_val = atan_val + cos_val

# Natural log of the sum
result = math.log(sum_val)

print("atan(22.855) =", atan_val)
print("cos(0.84886) =", cos_val)
print("sum =", sum_val)
print("ln(sum) =", result)